import type { PetId } from '../../shared/types'

/** Animations every pet has. Pets may add their own (Dusty: wash, rummage). */
export type AnimName =
  | 'idle'
  | 'idle_sad'
  | 'walk'
  | 'walk_sad'
  | 'run'
  | 'crawl'
  | 'sit'
  | 'sleep'
  | 'starving'
  | 'jump_up'
  | 'jump_down'
  | 'dragged'
  | 'eat'
  | 'happy'
  | 'hurt'
  | 'tap'
  | 'curious'
  | 'wash'
  | 'rummage'
  | 'slap'
export type Mood = 'idle' | 'blink' | 'happy' | 'hurt' | 'alert' | 'sad'
const MOODS: Mood[] = ['idle', 'blink', 'happy', 'hurt', 'alert', 'sad']

interface FrameMeta {
  file: string
  screen: [number, number]
  accent: [number, number] | null
}
interface PetMeta {
  cell: { w: number; h: number }
  anchor: { x: number; y: number }
  standHeight: number
  eyes: { w: number; h: number }
  accent: string | null
  anims: Record<string, { fps: number; loop: boolean; frames: FrameMeta[] }>
}

/** Every pet's frames.json, generated by scripts/generate-textures.ts. */
const METAS = import.meta.glob('../../../assets/pets/*/frames.json', { eager: true, import: 'default' }) as Record<string, PetMeta>

export interface Frame {
  img: HTMLImageElement
  /** Top-left of the eye area, in frame pixels. */
  screen: [number, number]
  /** Top-left of the accent light (Catbot's bell), if the pet has one. */
  accent: [number, number] | null
}

export interface Anim {
  frames: Frame[]
  fps: number
  loop: boolean
}

export interface SpriteSet {
  id: PetId
  cellW: number
  cellH: number
  /** The pet's feet (bottom centre) inside each frame. */
  anchorX: number
  anchorY: number
  /** Standing height in frame pixels (ears to paws). */
  standHeight: number
  anims: Partial<Record<AnimName, Anim>> & Record<'idle', Anim>
  eyes: Record<Mood, HTMLImageElement>
  accentOn: HTMLImageElement | null
  food: HTMLImageElement
  heart: HTMLImageElement
  zzz: HTMLImageElement
}

/** Load an image; a missing or broken file becomes a tiny magenta placeholder instead of failing. */
function load(src: string): Promise<HTMLImageElement> {
  return new Promise((resolve) => {
    const img = new Image()
    img.onload = () => resolve(img)
    img.onerror = () => {
      console.error(`[sprites] could not load ${src}`)
      const c = document.createElement('canvas')
      c.width = c.height = 2
      const ctx = c.getContext('2d')!
      ctx.fillStyle = '#ff00ff'
      ctx.fillRect(0, 0, 2, 2)
      const fallback = new Image()
      fallback.onload = () => resolve(fallback)
      fallback.src = c.toDataURL()
    }
    img.src = src
  })
}

/** Load a pet's frames (assets/pets/<id>) and the shared particle sprites (assets/textures). */
export async function loadSprites(id: PetId): Promise<SpriteSet> {
  const meta = METAS[`../../../assets/pets/${id}/frames.json`]
  if (!meta) throw new Error(`No sprites for pet "${id}"`)
  const dir = `./pets/${id}`
  const anims = {} as SpriteSet['anims']
  await Promise.all(
    Object.entries(meta.anims).map(async ([name, a]) => {
      anims[name as AnimName] = {
        fps: a.fps,
        loop: a.loop,
        frames: await Promise.all(a.frames.map(async (f) => ({ img: await load(`${dir}/${f.file}`), screen: f.screen, accent: f.accent })))
      }
    })
  )
  const eyes = Object.fromEntries(await Promise.all(MOODS.map(async (m) => [m, await load(`${dir}/eyes_${m}.png`)] as const))) as Record<
    Mood,
    HTMLImageElement
  >
  const [accentOn, food, heart, zzz] = await Promise.all([
    meta.accent ? load(`${dir}/${meta.accent}`) : Promise.resolve(null),
    load(`${dir}/food.png`),
    load('./textures/heart.png'),
    load('./textures/zzz.png')
  ])
  return {
    id,
    cellW: meta.cell.w,
    cellH: meta.cell.h,
    anchorX: meta.anchor.x,
    anchorY: meta.anchor.y,
    standHeight: meta.standHeight,
    anims,
    eyes,
    accentOn,
    food,
    heart,
    zzz
  }
}

/** Frame index of an animation after `t` seconds (looping, or holding the last frame). */
export function frameAt(anim: Anim, t: number): number {
  const i = Math.floor(t * anim.fps)
  return anim.loop ? i % anim.frames.length : Math.min(anim.frames.length - 1, i)
}

/**
 * Whole device pixels per sprite pixel for a requested on-screen height, so
 * the pixel art always stays crisp.
 */
export function pixelScale(sizeCss: number, standHeight: number, dpr: number): number {
  return Math.max(2, Math.round((sizeCss * dpr) / standHeight + 0.2))
}
